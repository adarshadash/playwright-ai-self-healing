import Anthropic from '@anthropic-ai/sdk';
import registry from '../../locators/locators.json';
import type { LocatorEntry } from '../../src/healing/types';
import type { Action, AnalyzedFile, By } from './types';

export interface Conversion {
  code: string;
  converter: 'rules' | 'claude';
  sleepsRemoved: number;
  brittleLocatorsReplaced: number;
  registryHits: number;
}

const BASE_URL = /^https?:\/\/(www\.)?saucedemo\.com/;

/** Maps every selector we already know (primary + fallbacks) to its registry key. */
const KNOWN_SELECTORS = new Map<string, string>();
for (const [key, entry] of Object.entries(registry as Record<string, LocatorEntry>)) {
  for (const s of [entry.selector, ...(entry.fallbacks ?? [])]) KNOWN_SELECTORS.set(normalise(s), key);
}

/**
 * Converter agent: IR → Playwright spec. Rule-based by default; uses Claude
 * when ANTHROPIC_API_KEY is set, with the rule-based output as a safety net.
 */
export class ConverterAgent {
  readonly name = 'Converter';

  async convert(analyzed: AnalyzedFile, source: string, feedback?: string[]): Promise<Conversion> {
    const rules = this.convertWithRules(analyzed);
    if (!process.env.ANTHROPIC_API_KEY || process.env.AI_MIGRATION === 'off') return rules;
    try {
      const code = await this.convertWithClaude(analyzed, source, rules.code, feedback);
      return code ? { ...rules, code, converter: 'claude' } : rules;
    } catch {
      return rules;
    }
  }

  convertWithRules(analyzed: AnalyzedFile): Conversion {
    let sleepsRemoved = 0;
    let brittleLocatorsReplaced = 0;
    let registryHits = 0;

    const tests = analyzed.tests.map((t) => {
      const lines: string[] = [];
      t.actions.forEach((a, i) => {
        if (a.kind === 'sleep') {
          sleepsRemoved++;
          lines.push(`    // removed ${a.raw} — Playwright auto-waits`);
          return;
        }
        if (a.kind === 'goto') {
          lines.push(`    await page.goto('${a.url.replace(BASE_URL, '') || '/'}');`);
          return;
        }
        if (a.kind === 'unknown') {
          lines.push(`    // TODO(migration): not converted automatically: ${a.raw.replace(/\s+/g, ' ')}`);
          return;
        }

        const { expr, viaRegistry, brittle } = locatorFor(a.by, a.value, t.name, i, a.kind === 'click');
        if (viaRegistry) registryHits++;
        if (brittle) brittleLocatorsReplaced++;

        switch (a.kind) {
          case 'fill':
            lines.push(`    await (${expr}).fill(${quote(a.text)});`);
            break;
          case 'click':
            lines.push(`    await (${expr}).click();`);
            break;
          case 'assertTextEquals':
            lines.push(`    await expect(${expr}).toHaveText(${quote(a.expected)});`);
            break;
          case 'assertTextContains':
            lines.push(`    await expect(${expr}).toContainText(${quote(a.expected)});`);
            break;
        }
      });
      return `  test('${humanise(t.name)}', async ({ page, healer }) => {\n${lines.join('\n')}\n  });`;
    });

    const code = [
      `// Generated by migration/orchestrator.ts from ${analyzed.file} — review before committing.`,
      `import { expect, test } from '../../src/fixtures';`,
      ``,
      `test.describe('${analyzed.className} (migrated from Selenium)', () => {`,
      tests.join('\n\n'),
      `});`,
      ``,
    ].join('\n');

    return { code, converter: 'rules', sleepsRemoved, brittleLocatorsReplaced, registryHits };
  }

  private async convertWithClaude(analyzed: AnalyzedFile, source: string, draft: string, feedback?: string[]) {
    const client = new Anthropic();
    const prompt = [
      'Convert this Selenium/TestNG Java test into an idiomatic Playwright Test TypeScript spec.',
      'Rules:',
      "- import { expect, test } from '../../src/fixtures'; fixtures provide { page, healer }.",
      "- Use `await healer.get('<registry key>')` when a locator matches one of the registry keys below; otherwise page.locator / getByRole.",
      '- No hard waits (no waitForTimeout); use web-first assertions (await expect(locator).toHaveText(...)).',
      '- Replace absolute XPath with a stable selector.',
      '- Keep one test per @Test method with readable titles.',
      'Return ONLY the TypeScript file inside one ```ts block.',
      '',
      `Registry keys: ${Object.keys(registry).join(', ')}`,
      `Analyzer smells: ${analyzed.smells.join('; ') || 'none'}`,
      feedback?.length ? `Reviewer feedback to fix: ${feedback.join('; ')}` : '',
      '',
      'Java source:',
      '```java',
      source,
      '```',
      '',
      'Rule-based draft you may improve:',
      '```ts',
      draft,
      '```',
    ].join('\n');

    const response = await client.messages.create({
      model: process.env.CLAUDE_MODEL ?? 'claude-sonnet-5-5',
      max_tokens: 4000,
      messages: [{ role: 'user', content: prompt }],
    });
    const text = response.content.map((b) => (b.type === 'text' ? b.text : '')).join('');
    return text.match(/```(?:ts|typescript)\n([\s\S]*?)```/)?.[1] ?? null;
  }
}

function locatorFor(by: By, value: string, testName: string, index: number, isClick: boolean) {
  const css = toCss(by, value);
  const key = css ? KNOWN_SELECTORS.get(normalise(css)) : undefined;
  if (key) return { expr: `await healer.get('${key}')`, viaRegistry: true, brittle: false };

  if (by === 'xpath' && value.startsWith('/html')) {
    // Absolute XPath breaks on any layout change: hand it to the self-healer
    // with a description, so it is replaced at runtime and logged for review.
    const description = /\/(input|button)(\[\d+\])?$/.test(value) && isClick
      ? 'Submit button of the form'
      : `Element used in ${humanise(testName)}`;
    return {
      expr: `await healer.get({ key: 'legacy.${testName}.${index}', selector: ${quote('xpath=' + value)}, description: ${quote(description)} })`,
      viaRegistry: false,
      brittle: true,
    };
  }
  return { expr: `page.locator(${quote(css ?? `xpath=${value}`)})`, viaRegistry: false, brittle: false };
}

function toCss(by: By, value: string): string | undefined {
  switch (by) {
    case 'id':
      return `#${value}`;
    case 'className':
      return `.${value.trim().split(/\s+/).join('.')}`;
    case 'name':
      return `[name="${value}"]`;
    case 'cssSelector':
      return value;
    case 'linkText':
      return `a:text-is("${value}")`;
    default:
      return undefined;
  }
}

function normalise(selector: string) {
  return selector.replace(/'/g, '"').replace(/\s+/g, '');
}

function quote(s: string) {
  return `'${s.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
}

function humanise(methodName: string) {
  return methodName.replace(/([A-Z])/g, ' $1').toLowerCase().trim();
}
